/** Currently active language code */
let _lang = localStorage.getItem('sc_lang') || 'en';

/**
 * t(key, vars?) — look up a translation key in the active language,
 * fall back to English if missing, then fall back to the key itself.
 * Supports {{placeholder}} interpolation.
 */
function t(key, vars) {
  const dict = TRANSLATIONS[_lang] || TRANSLATIONS.en;
  const en   = TRANSLATIONS.en;
  let str = dict[key] ?? en[key] ?? key;
  if (vars) {
    Object.entries(vars).forEach(([k, v]) => {
      str = str.replace(new RegExp('{{' + k + '}}', 'g'), v);
    });
  }
  return str;
}

/**
 * setLang(code) — switch language, persist to localStorage,
 * then re-apply all static i18n labels on the page.
 */
function setLang(code) {
  if (!TRANSLATIONS[code]) return;
  _lang = code;
  localStorage.setItem('sc_lang', code);
  applyStaticTranslations();
}

/**
 * getLang() — return current language code.
 */
function getLang() { return _lang; }

/**
 * applyStaticTranslations() — walk every element that has a data-i18n attribute
 * and update its text content (or placeholder/title).
 * Also updates dynamic parts of the page title, page-title bar, and nav labels.
 */
function applyStaticTranslations() {
  // 1. data-i18n="key" → textContent
  document.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = t(el.dataset.i18n);
  });
  // 2. data-i18n-placeholder="key" → placeholder attr
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  // 3. data-i18n-title="key" → title attr
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    el.title = t(el.dataset.i18nTitle);
  });
  // 4. Update nav item labels (they are dynamically created)
  document.querySelectorAll('.nav-item[data-route]').forEach(el => {
    const routeKey = 'nav_' + el.dataset.route;
    const span = el.querySelector('span:last-child');
    if (span) span.textContent = t(routeKey);
  });
  // 5. Update nav section group labels
  const groupMap = {
    'Overview': t('nav_overview'),
    'Master Data': t('nav_master_data'),
    'Intelligence': t('nav_intelligence'),
    'Recovery': t('nav_recovery'),
  };
  document.querySelectorAll('.nav-section').forEach(el => {
    const translated = groupMap[el.textContent.trim()];
    if (translated) el.textContent = translated;
    // also update by looking at the data attribute we'll set
    if (el.dataset.group) el.textContent = t(el.dataset.group);
  });
  // 6. Update topbar page title for current route
  if (window.currentRoute && window.ROUTES) {
    const meta = window.ROUTES.find(r => r.id === window.currentRoute);
    if (meta) {
      const titleEl = document.getElementById('page-title');
      if (titleEl) titleEl.textContent = t('nav_' + meta.id);
    }
  }
  // 7. Update language selector to show current
  const sel = document.getElementById('lang-select');
  if (sel && sel.value !== _lang) sel.value = _lang;
  // 8. Update html[lang]
  document.documentElement.lang = _lang;
}
